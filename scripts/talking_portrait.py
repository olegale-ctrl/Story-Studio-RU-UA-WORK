"""CPU-only talking portrait using external Wav2Lip and a pre-rendered voice WAV.

Use the WAV generated by Story Studio Sprint 26 (output/.../media/voice1.wav).
No model downloads or untrusted code execution happen automatically.
"""
from __future__ import annotations
import argparse
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from integrations.wav2lip_cpu import render_talking_portrait


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Generate lip-synced portrait video on CPU")
    p.add_argument("--portrait", type=Path, required=True)
    p.add_argument("--audio", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--wav2lip-dir", type=Path, required=True)
    p.add_argument("--checkpoint", type=Path, required=True)
    p.add_argument("--wav2lip-python", type=Path, required=True)
    p.add_argument("--ffmpeg", type=Path)
    p.add_argument("--timeout", type=int, default=7200)
    args = p.parse_args(argv)
    try:
        result = render_talking_portrait(
            face=args.portrait, audio=args.audio, output=args.output,
            checkout=args.wav2lip_dir, checkpoint=args.checkpoint,
            python_exe=args.wav2lip_python, ffmpeg_exe=args.ffmpeg,
            timeout_seconds=args.timeout)
        print("VIDEO:", result)
        return 0
    except (OSError, ValueError, RuntimeError) as exc:
        print("ERROR:", exc, file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
