def vector_graph(name):
    if name.startswith('source_'):
        g, n, active = source_graph()
        if name == 'source_missing':
            g.records.remove(g.refs[key(n['S2'])])
        return g, n['S3'], active, []
    if name.startswith('brief_'):
        g, n, active, heads = brief_graph()
        if name == 'brief_head_stale':
            heads = [add_selection(g, n, n['K3'], previous=heads[0])]
        return g, n['B1'], active, heads
    mode = 'text_only' if name == 'text_current' else 'changed_angle' if name == 'angle_stale' else 'changed_hook'
    g, n, active = creative_graph(mode, external=name == 'eref_invalid')
    if name not in ('g02_stale', 'qa_corrupt'):
        active += [n['Qa']]
    if name == 'qa_corrupt':
        g.refs[key(n['Qa'])]['payload']['statement'] = 'Changed immutable bytes'
    return g, n['K3'], active, []


class CurrentnessLiteralVectors(unittest.TestCase):
    def check_vector(self, index):
        name, kind, prefix, revision, sha, graph_sha, context_sha, state, codes = VECTORS[index]
        g, root, active, heads = vector_graph(name)
        self.assertEqual({'type':kind, 'id':prefix + '-2222-4222-8222-222222222222',
                          'revision':revision, 'sha256':sha}, root)
        context = {'active_input_refs':active, 'selection_head_refs':heads}
        # Independent stdlib JSON/hash fixture oracle and accepted SI codec each
        # compared to literal constants, not merely to each other.
        self.assertEqual(graph_sha, digest(g.records))
        self.assertEqual(context_sha, digest(context))
        self.assertEqual(graph_sha, canonical_si_sha256(g.records))
        self.assertEqual(context_sha, canonical_si_sha256(context))
        before = deepcopy((g.records, root, active, heads))
        if name not in ('source_missing', 'qa_corrupt'):
            expected_audit = g.closure([root] + active + heads)
            self.assertEqual(expected_audit, resolve_si_closure(g.records, [root] + active + heads))
            self.assertEqual(expected_audit, verify_si_provenance(g.records, [root] + active + heads))
        self.assertEqual({'currentness':state, 'reason_codes':list(codes)},
                         check_si_currentness(g.records, root, active, heads))
        self.assertEqual(before, (g.records, root, active, heads))

    def test_01_source_current(self): self.check_vector(0)
    def test_02_source_missing(self): self.check_vector(1)
    def test_03_exact_g02_stale(self): self.check_vector(2)
    def test_04_exact_g02_restored_current(self): self.check_vector(3)
    def test_05_text_edit_current(self): self.check_vector(4)
    def test_06_corrupt_original_qa_invalid(self): self.check_vector(5)
    def test_07_incompatible_angle_stale(self): self.check_vector(6)
    def test_08_eref_invalid(self): self.check_vector(7)
    def test_09_brief_current(self): self.check_vector(8)
    def test_10_used_selection_changed_stale(self): self.check_vector(9)


